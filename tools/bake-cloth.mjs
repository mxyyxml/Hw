// Packs tools/cloth-sim.py's bake.json into js/clothBake.js (base64 Int16 deltas).
//   node tools/bake-cloth.mjs <folder-with-bake.json>
import fs from 'fs';
const bake = JSON.parse(fs.readFileSync(process.argv[2] + '/bake.json', 'utf8'));
let s = '// Generated by tools/cloth-sim.py + tools/bake-cloth.mjs — Blender cloth-simulation drape for each\n// garment on each body: key → { n: vertex count, d: base64 Int16 xyz deltas in 0.1 mm }.\nexport const CLOTH_BAKE = {\n';
// the sim drapes an A-posed, standing body; on a crouched skater big hem flares read as a skirt: cap at 3.5 cm
const MAX = 350;
for (const v of Object.values(bake)) for (let i = 0; i < v.d.length; i += 3) {
  const l = Math.hypot(v.d[i], v.d[i + 1], v.d[i + 2]);
  if (l > MAX) for (let k = 0; k < 3; k++) v.d[i + k] = Math.round(v.d[i + k] * MAX / l);
}
for (const [k, v] of Object.entries(bake).sort()) s += `  '${k}': { n: ${v.n}, d: '${Buffer.from(Int16Array.from(v.d).buffer).toString('base64')}' },\n`;
fs.writeFileSync('js/clothBake.js', s + '};\n');
console.log(Object.keys(bake).length, 'garments,', (s.length / 1024).toFixed(0), 'KB');
